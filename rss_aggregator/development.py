"""Run the shared, check-only development gate and guarded hook setup."""

import json
import os
import subprocess
import sys
from pathlib import Path

import click

_PRE_COMMIT_HEADER = "# File generated by pre-commit: https://pre-commit.com"
_PRE_COMMIT_ID = "# ID: 138fd403232d2ddd5efb44317e38bf03"


def _project(root: Path | None) -> Path:
    """Resolve an explicit project directory or the current working directory."""
    return (root if root is not None else Path.cwd()).resolve()


def _run(arguments: list[str], root: Path) -> subprocess.CompletedProcess[str]:
    """Run tools without ambient import/test overrides and relay diagnostics."""
    environment = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith("PYTEST_") and key not in {"PYTHONPATH", "PYTHONHOME"}
    }
    environment["PYTHONDONTWRITEBYTECODE"] = "1"
    try:
        result = subprocess.run(
            arguments,
            cwd=root,
            env=environment,
            text=True,
            capture_output=True,
            check=False,
        )
    except OSError as error:
        result = subprocess.CompletedProcess(arguments, 127, "", str(error))
    for output in (result.stdout, result.stderr):
        if output:
            print(output, file=sys.stderr, end="" if output.endswith("\n") else "\n")
    return result


def _python(project: Path) -> str:
    """Select the project's uv environment without resolving interpreter symlinks.

    Missing environments fail at process launch rather than falling back to the
    caller's packages. Synchronize the selected checkout with uv before use.
    """
    executable = "Scripts/python.exe" if os.name == "nt" else "bin/python"
    return str(project / ".venv" / executable)


def _tools(root: Path | None, operations: list[tuple[str, list[str]]]) -> dict:
    """Collect every operation's exit status without short-circuiting failures."""
    project = _project(root)
    results = []
    for name, arguments in operations:
        result = _run([_python(project), "-I", "-B", "-m", *arguments], project)
        results.append({"name": name, "returncode": result.returncode})
    return {"ok": all(item["returncode"] == 0 for item in results), "checks": results}


def check(root: Path | None = None) -> dict:
    """Check the complete default test suite, lint, and format without fixing files.

    Returns
    -------
    dict
        Overall success and each tool's exit status. All checks run even when an
        earlier check fails; child output is diagnostic stderr, not JSON stdout.
        Tools use the selected checkout's local ``.venv``, never the caller's
        editable installation. This operation does not create or sync it.
        Ruff fixes and fix-only mode are explicitly disabled, including when
        the selected checkout's configuration enables them.
    """
    return _tools(
        root,
        [
            ("pytest", ["pytest", "-p", "no:cacheprovider", "-m", "not live"]),
            ("lint", ["ruff", "check", "--no-fix", "--no-fix-only", "--no-cache"]),
            ("format", ["ruff", "format", "--check", "--no-cache"]),
        ],
    )


def format_code(root: Path | None = None) -> dict:
    """Explicitly format project Python files with Ruff, without lint fixes."""
    return _tools(root, [("format", ["ruff", "format", "--no-cache"])])


def fix(root: Path | None = None) -> dict:
    """Explicitly apply Ruff's safe lint fixes, without unsafe fixes or formatting."""
    return _tools(
        root,
        [("fix", ["ruff", "check", "--fix", "--no-unsafe-fixes", "--no-cache"])],
    )


def _refusal(reason: str) -> dict:
    """Explain a preserved hook arrangement and its manual resolution."""
    return {
        "ok": False,
        "active": False,
        "reason": reason,
        "next_step": (
            "Preserve and resolve the existing hook arrangement manually, then "
            "rerun uv run --locked rss-dev setup. No hooks were changed."
        ),
    }


def _owned_hook(path: Path) -> bool:
    """Recognize the standard pre-commit pre-push hook for this configuration."""
    if not path.is_file() or path.is_symlink():
        return False
    try:
        content = path.read_text()
    except (OSError, UnicodeError):
        return False
    return (
        _PRE_COMMIT_HEADER in content.splitlines()
        and _PRE_COMMIT_ID in content.splitlines()
        and "ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-push)"
        in content.splitlines()
    )


def setup(root: Path | None = None) -> dict:
    """Activate pre-push checks only when Git's existing hooks can be preserved.

    A repository without remotes remains inactive and requires an explicit
    rerun after a remote is added. Custom paths, symlinks, foreign hooks, and
    legacy or nonexecutable hooks require manual resolution; setup never chains
    or deletes them.
    Hook installation expects the selected checkout's synchronized local .venv.
    """
    project = _project(root)
    repository = _run(["git", "rev-parse", "--show-toplevel"], project)
    if repository.returncode:
        return _refusal("The project must be a working Git repository.")
    if Path(repository.stdout.strip()).resolve() != project:
        return _refusal("Select the Git repository root with --project.")
    remotes = _run(["git", "remote"], project)
    if remotes.returncode:
        return _refusal("Could not inspect Git remotes.")
    if not remotes.stdout.strip():
        return {
            "ok": True,
            "active": False,
            "reason": "No Git remote is configured; no hook was installed.",
            "next_step": "Add a remote, then rerun uv run --locked rss-dev setup.",
        }
    custom = _run(["git", "config", "--get-all", "core.hooksPath"], project)
    if custom.returncode not in (0, 1):
        return _refusal("Could not inspect core.hooksPath.")
    if custom.returncode == 0:
        return _refusal("core.hooksPath is configured; custom hooks are preserved.")
    location = _run(["git", "rev-parse", "--git-path", "hooks"], project)
    if location.returncode:
        return _refusal("Could not locate Git hooks.")
    hooks = Path(location.stdout.strip())
    if not hooks.is_absolute():
        hooks = project / hooks
    if hooks.is_symlink() or (hooks.exists() and not hooks.is_dir()):
        return _refusal("The Git hooks directory is a symlink or non-directory.")
    hook = hooks / "pre-push"
    legacy = hooks / "pre-push.legacy"
    if legacy.exists() or legacy.is_symlink():
        return _refusal("A legacy pre-push hook exists.")
    if hook.is_symlink() or (hook.exists() and not _owned_hook(hook)):
        return _refusal("An existing foreign or symlinked pre-push hook exists.")
    if hook.exists():
        if not os.access(hook, os.X_OK):
            return _refusal("The existing pre-push hook is not executable.")
        # Even a recognized generated hook may have developer-owned extensions.
        # Preserve the existing script rather than overwriting it during setup.
        return {"ok": True, "active": True}
    result = _run(
        [
            _python(project),
            "-I",
            "-B",
            "-m",
            "pre_commit",
            "install",
            "--hook-type",
            "pre-push",
        ],
        project,
    )
    return {"ok": result.returncode == 0, "active": result.returncode == 0}


def _emit(result: dict) -> None:
    """Write one JSON result and propagate logical failure to the command exit."""
    click.echo(json.dumps(result, indent=2))
    if not result["ok"]:
        raise click.exceptions.Exit(1)


@click.group()
def main() -> None:
    """Manage development checks and guarded pre-push hook activation."""


@main.command("check")
@click.option("--project", type=click.Path(path_type=Path, file_okay=False))
def check_command(project: Path | None) -> None:
    """Run all baseline checks without changing project files."""
    _emit(check(project))


@main.command("setup")
@click.option("--project", type=click.Path(path_type=Path, file_okay=False))
def setup_command(project: Path | None) -> None:
    """Activate pre-push hooks after inspecting existing Git arrangements."""
    _emit(setup(project))


@main.command("format")
@click.option("--project", type=click.Path(path_type=Path, file_okay=False))
def format_command(project: Path | None) -> None:
    """Explicitly format Python files, independently of lint fixes."""
    _emit(format_code(project))


@main.command("fix")
@click.option("--project", type=click.Path(path_type=Path, file_okay=False))
def fix_command(project: Path | None) -> None:
    """Explicitly apply only Ruff's safe lint fixes."""
    _emit(fix(project))
